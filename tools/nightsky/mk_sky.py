# V16a: night sky data from d3-celestial (BSD-3-Clause, Olaf Frohn): Hipparcos stars to mag 6 and the Milky Way outline levels.
# Writes src/33_skydata.js: stars packed (RA, Dec as uint16, mag, B-V as uint8; base64) and the Milky Way as an equirectangular
# grayscale PNG in equatorial coordinates (RA left→right 0..360, Dec top +90 → bottom −90), data URI.
import json, sys, os, base64, io, struct, math
import numpy as np
from PIL import Image, ImageDraw, ImageFilter
SP = sys.argv[1]; OUT = sys.argv[2]
D = os.path.join(SP, 'dl_d3cel', 'package', 'data')
stars = json.load(open(os.path.join(D, 'stars.6.json')))['features']
buf = bytearray()
n = 0
for f in sorted(stars, key=lambda f: f['properties']['mag']):
    ra, dec = f['geometry']['coordinates']; ra %= 360
    mag = float(f['properties']['mag']); 
    try: bv = float(f['properties']['bv'])
    except Exception: bv = 0.6
    buf += struct.pack('<HHBB', int(round(ra / 360 * 65535)) & 0xffff, int(round((dec + 90) / 180 * 65535)), max(0, min(255, int(round((mag + 2) * 25)))), max(0, min(255, int(round((bv + 0.5) * 100)))))
    n += 1
print('stars', n, 'bytes', len(buf))
# ---- Milky Way: rasterize in an azimuthal equidistant plane centred on the north galactic pole (the band becomes an annulus) ----
T = np.array([[-0.0548755604, -0.8734370902, -0.4838350155], [0.4941094279, -0.4448296300, 0.7469822445], [-0.8676661490, -0.1980763734, 0.4559837762]])
def eq2vec(ra, dec):
    ra = np.radians(ra); dec = np.radians(dec); return np.stack([np.cos(dec) * np.cos(ra), np.cos(dec) * np.sin(ra), np.sin(dec)], -1)
N = 2400; Rmax = math.pi
def plane(v):   # galactic vector → plane pixel coords
    g = v @ T.T; b = np.arcsin(np.clip(g[..., 2], -1, 1)); l = np.arctan2(g[..., 1], g[..., 0]); r = math.pi / 2 - b
    return np.stack([N / 2 + r * np.cos(l) / Rmax * (N / 2), N / 2 - r * np.sin(l) / Rmax * (N / 2)], -1)
mw = json.load(open(os.path.join(D, 'milkyway.json')))['features']
acc = np.zeros((N, N), np.float32)
W = {'ol1': 0.22, 'ol2': 0.2, 'ol3': 0.2, 'ol4': 0.19, 'ol5': 0.19}
for f in mw:
    g = f['geometry']; rings = g['coordinates'] if g['type'] == 'Polygon' else [r for p in g['coordinates'] for r in p]
    mask = np.zeros((N, N), bool)
    for r in rings:
        a = np.array(r, float); p = plane(eq2vec(a[:, 0], a[:, 1]))
        im = Image.new('1', (N, N), 0); ImageDraw.Draw(im).polygon([tuple(q) for q in p], fill=1)
        mask ^= np.array(im, bool)
    acc += mask * W[f['id']]
    c = np.array(rings[0], float); print(f['id'], 'rings', len(rings), 'area frac %.3f' % mask.mean())
base = Image.fromarray((np.clip(acc, 0, 1) * 255).astype(np.uint8))
bl = lambda r: np.array(base.filter(ImageFilter.GaussianBlur(r)), np.float32) / 255
P = bl(3) * 0.45 + bl(9) * 0.35 + bl(26) * 0.35   # fine structure, soft band, wide glow around it
# resample to equirect RA/Dec
WE, HE = 1024, 512
ra = (np.arange(WE) + 0.5) / WE * 360; dec = 90 - (np.arange(HE) + 0.5) / HE * 180
RA, DE = np.meshgrid(ra, dec); q = plane(eq2vec(RA, DE))
xi = np.clip(q[..., 0], 0, N - 1.001); yi = np.clip(q[..., 1], 0, N - 1.001); x0 = xi.astype(int); y0 = yi.astype(int); fx = xi - x0; fy = yi - y0
v = P[y0, x0] * (1 - fx) * (1 - fy) + P[y0, x0 + 1] * fx * (1 - fy) + P[y0 + 1, x0] * (1 - fx) * fy + P[y0 + 1, x0 + 1] * fx * fy
# a little structure inside the band (dust lanes are already in the levels); gentle gamma
out = Image.fromarray((np.clip(v, 0, 1) ** 0.85 * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2))
out.save(os.path.join(SP, 'dnprep', 'milkyway_eq.png'))
bio = io.BytesIO(); out.save(bio, 'PNG', optimize=True); png = bio.getvalue(); print('milky way png', len(png))
js = ('// ===================== V16a night sky data (generated by dnprep/mk_sky.py) =====================\n'
      '// Stars: Hipparcos catalogue (ESA), mag <= 6, and the Milky Way outline levels as prepared by Olaf Frohn for d3-celestial\n'
      '// (BSD-3-Clause, https://github.com/ofrohn/d3-celestial). Stars packed per star: RA, Dec (uint16), (mag+2)*25, (B-V+0.5)*100 (uint8).\n'
      'const SKYDATA = { n: %d, stars: "%s", mw: "data:image/png;base64,%s" };\n' % (n, base64.b64encode(bytes(buf)).decode(), base64.b64encode(png).decode()))
open(OUT, 'w').write(js); print('wrote', OUT, len(js))
